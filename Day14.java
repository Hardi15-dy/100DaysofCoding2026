public class day14 {
    public static void main(String[] args) {

        // operator aritmatika penjumlahan dan pengurangan
        int a = 10;
        int b = 20;

        int hasilPenjumlahan = a + b;
        int hasilPengurangan = b - a;

        System.out.printf("Hasil penjumlahan dari %d + %d = %d%n", a, b, hasilPenjumlahan);
        System.out.printf("Hasil pengurangan dari %d - %d = %d%n", b, a, hasilPengurangan);
    }
}
