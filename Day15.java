public class day15 {
    public static void main(String[] args) {
        
        // operator aritmatika perkalian dan pembagian
        /*
        Dalam operator aritmatika perkalian dan pembagian, kita dapat menggunakan simbol * untuk perkalian dan simbol / untuk pembagian.
        */
        int a = 10;
        int b = 20;

        int hasilPerkalian = a * b;
        int hasilPembagian = b / a;

        System.out.printf("Hasil perkalian dari %d * %d = %d%n", a, b, hasilPerkalian);
        System.out.printf("Hasil pembagian dari %d / %d = %d%n", b, a, hasilPembagian);
    }
}
