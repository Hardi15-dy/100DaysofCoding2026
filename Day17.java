public class day17 {
	public static void main(String[] args) {
		// Day 17
		// operator penugasan



		int a = 10;

		System.out.println("Sebelum pakai operator penugasan a : "+a);
		a += 20;
		System.out.println("Sesudah pakai operator penugasan a + 20 : "+a);
		a *= 2;
		System.out.println("Sesudah pakai operator penugasan a * 2 : "+a);
		a /= 2;
		System.out.println("Sesudah pakai operator penugasan a / 2 : "+a);
		a -= 10;
		System.out.println("Sesudah pakai operator penugasan a - 10 : "+a);
	}
}
