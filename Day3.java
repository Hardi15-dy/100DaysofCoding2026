public class day3 {
    /**
     * @author HARDI
     */
    public static void main(String[] args) {   
        //Day 3 - Escape Sequence
        //Saya menambahkan 7 escape sequence di bawah ini

        //INI NORMAL
        System.out.println("Nama saya adalah HARDI");

        //INI escape baris baru
        System.out.println("Nama saya \nadalah HARDI");
        
        //INI escape tab
        System.out.println("Nama saya \tadalah HARDI");
        
        //INI escape agar ada kutipan
        System.out.println("Nama saya adalah \"HARDI\"");
        
        //INI escape agar ada backslash
        System.out.println("Nama saya adalah \\HARDI");

        //INI escape agar ada backspace
        System.out.println("Nama saya adalah \bHARDI");

        //INI escape agar ada form feed
        System.out.println("Nama saya adalah \fHARDI");
        
        //INI escape agar ada carriage return atau kembali ke awal baris
        System.out.println("Nama saya adalah \rHARDI");
    }
}
