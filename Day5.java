public class day5 {
    /**
     * @author HARDI
     */
    public static void main(String[] args) {
        //Day 5 - Tipe Data Numerik Bilangan Pecahan
        float f= 3.14f;
        double d= 3.14;

        System.out.println("===== CONTOH BILANGAN NUMERIK PECAHAN =====");
        System.out.println("Nilai float: "+f);
        System.out.println("Nilai double: "+d);

        System.out.println("");

        System.out.println("===== Value MIN DAN MAX tipe data numerik bilangan pecahan  =====");
        System.out.println("Contoh bilangan float dari "+Float.MIN_VALUE+" sampai "+Float.MAX_VALUE);
        System.out.println("Contoh bilangan Double dari "+Double.MIN_VALUE+" sampai "+Double.MAX_VALUE);
    }
}
