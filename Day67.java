public class day67 {
    public static void main(String[] args) {
        // Day 67
        // Membuat pola persegi


        System.out.println("\n=== PERSEGI ===\n");
        int sisi = 5;

        for (int i = 1; i <= sisi; i++) {
            for (int j = 1; j <= sisi; j++) {
                System.out.print(" * ");
            }
            System.out.println();
        }
        System.out.println();
    }
}
